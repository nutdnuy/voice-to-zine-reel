"""Resolve story.json (times anchored to the voice) into src/config.js (CFG, absolute seconds) and piece.json.

usage: python resolve_story.py <project dir>
reads <project>/story.json, voice.json (cleaned), edl.json

Time anchors (cleaned-take time):
  12.5            absolute seconds
  "l05"           line l05 starts          "l05.end"   line l05 ends
  "l05@14"        the 14th recognised word of l05 starts (Thai "words" are character groups: read voice.json)
  "start"         this scene's start       "end0"      the end card's start
  "button" / "button.end"                  the reused closing line
  any of these + or - an offset: "l05@14-0.1", "start+0.4", "l03.end+0.2"
"""
import json
import os
import re
import sys

root = sys.argv[1]
st = json.load(open(os.path.join(root, "story.json")))
V = json.load(open(os.path.join(root, "voice.json")))
E = json.load(open(os.path.join(root, "edl.json")))
L = {l["id"]: l for l in V["lines"]}
btn = E.get("button")
end_card = st.get("end_card")
end0 = round(E["speech_end"] + (end_card or {}).get("after_speech", 0.35), 3) if end_card else None


def at(x, scene_t0=None):
    if isinstance(x, (int, float)):
        return float(x)
    m = re.fullmatch(r"\s*([A-Za-z0-9_.@]+?)\s*([+-]\s*[0-9.]+)?\s*", x)
    if not m:
        raise SystemExit(f"bad time anchor: {x!r}")
    base, off = m.group(1), float(m.group(2).replace(" ", "")) if m.group(2) else 0.0
    if base == "start":
        v = scene_t0
    elif base == "end0":
        v = end0
    elif base == "button":
        v = btn["at"]
    elif base == "button.end":
        v = btn["end"]
    elif "@" in base:
        lid, k = base.split("@"); v = L[lid]["words"][int(k)]["t0"]
    elif base.endswith(".end"):
        v = L[base[:-4]]["t1"]
    else:
        if base not in L:
            raise SystemExit(f"unknown line {base!r} in anchor {x!r} (dropped by the edit?)")
        v = L[base]["t0"]
    if v is None:
        raise SystemExit(f"anchor {x!r} needs a context it does not have")
    return round(v + off, 3)


def scene(sc, t0):
    return {"plate": sc["plate"], "t0": t0, "ch": sc.get("chapter", ""),
            "cam": [[at(k[0], t0)] + list(k[1:]) for k in sc.get("cam", [["start", 512, 760, 1.0]])],
            "marks": [[m[0], at(m[1], t0)] + list(m[2:]) for m in sc.get("marks", [])],
            "keys": [[s[0], at(s[1], t0)] + list(s[2:]) for s in sc.get("strips", [])]}


scenes = []
for sc in st["scenes"] + ([end_card] if end_card else []):
    if re.match(r"\s*(no\.?|#|ep\.?|part)\s*\d+", sc.get("chapter", ""), re.I):
        raise SystemExit(f"chapter label {sc['chapter']!r}: no numbering (Nuth, 2026-10-12) — use topic words only")
for sc in st["scenes"]:
    t0 = at(sc.get("start", 0))
    scenes.append(scene(sc, t0))
for a, b in zip(scenes, scenes[1:]):
    if b["t0"] <= a["t0"]:
        raise SystemExit(f"scene {b['plate']} starts before {a['plate']}")
end_caps = []
if end_card:
    scenes.append(scene(end_card, end0))
    if btn:
        end_caps = [[end0 + 0.1, btn["at"] - 0.05, end_card.get("caption", "")], [btn["at"] - 0.05, btn["end"] + 0.3, end_card.get("button_caption", btn.get("text", ""))]]
    else:
        end_caps = [[end0 + 0.1, E["new_duration"], end_card.get("caption", "")]]
logo_t = None
if st.get("logo", True):
    logo_t = round((btn["end"] + 0.15) if (btn and end_card) else ((end0 + 2.5) if end_card else E["speech_end"] + 0.6), 3)
qf = st.get("quiet_from")
quiet_from = scenes[int(qf.split(":")[1])]["t0"] if isinstance(qf, str) and qf.startswith("scene:") else (at(qf) if qf is not None else scenes[-2 if end_card else -1]["t0"])
cfg = {
    "title": st["title"], "tagline": st.get("tagline", ""), "duration": E["new_duration"],
    "payoff": at(st["payoff"]), "quiet_from": quiet_from, "end0": end0, "logo_t": logo_t,
    "button": ({"at": btn["at"], "end": btn["end"], "caption": end_card.get("button_caption", btn.get("text", "")) if end_card else btn.get("text", "")} if btn else None),
    "end_card": bool(end_card), "scenes": scenes, "end_caps": end_caps,
    "captions": st.get("captions", {}), "accents": [[at(a[0]), a[1]] for a in st.get("accents", [])],
    "logo_top": st.get("logo_top", True),
}
os.makedirs(os.path.join(root, "src"), exist_ok=True)
open(os.path.join(root, "src", "config.js"), "w").write("// generated by scripts/resolve_story.py from story.json — edit story.json, not this file\nconst CFG = " + json.dumps(cfg, ensure_ascii=False) + ";\n")
d = E["new_duration"]
json.dump({"name": os.path.basename(os.path.abspath(root)), "title": st["title"], "format": {"width": 1080, "height": 1920, "fps": 24, "duration": d, "frames": round(d * 24)},
           "formats": ["9:16"], "storyFormat": "voice-led chronology (hard cuts)", "style": "vox-paper",
           "build": ["src/head.html", "kit/core.js", "style", "src/config.js", "src/zine.js", "src/tail.html"],
           "review": {"safe": {"top": 250, "bottom": 420, "right": 140}, "refs": {}, "deadMax": 4.5}},
          open(os.path.join(root, "piece.json"), "w"), indent=1, ensure_ascii=False)
print(f"{len(scenes)} scenes, payoff {cfg['payoff']}s, quiet from {quiet_from}s, logo {logo_t}s, duration {d}s -> src/config.js, piece.json")
missing = [s["plate"] for s in scenes if not os.path.exists(os.path.join(root, "gen", s["plate"] + ".png"))]
if missing:
    print("warning: plates not generated yet:", ", ".join(sorted(set(missing))))
